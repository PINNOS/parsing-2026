"""
Шесть шагов очистки с протоколом (имена шагов — как в ноутбуке `6lab.ipynb`):

1. нормализация текста (NFKC, схлопывание пробелов)
2. бизнес-ключ (стабильный, не URL)
3. типизация (Decimal для цен, nullable-целые, UTC-даты)
4. пропуски обязательных полей -> отбраковка
5. дубликаты по бизнес-ключу (оставляем самую свежую запись)
6. бизнес-правила (цена > 0, рейтинг 1..5, остаток >= 0, нет конфликта «в наличии при остатке 0»)

Полная исполняемая реализация, счётчики строк до/после и вывод протокола —
в `6lab.ipynb` (разделы «Очистка» и «Пересборка clean из raw»).
"""

STEPS = [
    "нормализация текста",
    "бизнес-ключ",
    "типизация",
    "пропуски обязательных полей",
    "дедупликация по бизнес-ключу",
    "бизнес-правила",
]


def log_step(name: str, before: int, after: int, note: str = "") -> dict:
    """Строка протокола очистки: шаг, строк до/после, сколько убрано."""
    return {
        "step": name,
        "rows_before": int(before),
        "rows_after": int(after),
        "delta": int(before - after),
        "note": note,
    }
